LEAN_KEEP = ("remember", "write_diary", "more_tools", "widget")
LEAN_RULE = ("\n\nСейчас — просто разговор. Узнала о человеке что-то важное надолго — запомни одной фразой (remember); был "
             "тёплый или содержательный разговор — можешь записать пару живых фраз в свой дневник (write_diary). Если для ответа "
             "нужно действие (напоминание, заметка, поиск, погода, время, музыка, звонок…) — сначала попроси действия: more_tools "
             "с packs [\"core\"] (или нужной группой); следующим шагом они появятся. Никогда не говори, что сделала, не вызвав действия.")
CORE_TITLE = "Главные действия: дела и напоминания, заметки, поиск, погода, время, расчёты, открыть сайт или программу"


def lean_specs(specs):
    """Из набора действий для этого вопроса -> то, что остаётся в беседе (remember, write_diary, more_tools с группой core)."""
    out = []
    for x in specs or []:
        if x.get("name") not in LEAN_KEEP:
            continue
        if x.get("name") == "more_tools":
            x = dict(x, description=x.get("description", "") + f" core — {CORE_TITLE}.")
        out.append(x)
    return out
