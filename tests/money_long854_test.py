"""№854–856 (18.11): длинное письмо в несколько строк («Установи: … какой инструмент создал файл… почему получилось
двойное расширение») быстрый разбор денег принимал за «сколько я получил» — без модели отвечал «В этом месяце доходов не
записано». Человек: «чушь несёт», «збой». Теперь: письмо в несколько строк или длиннее 30 слов — не к деньгам;
«получилось» — не «получил»."""
import os, sys
from pathlib import Path
ROOT = Path(os.environ.get("DEWIAR_ROOT") or Path(__file__).resolve().parent.parent)
sys.path.insert(0, str(ROOT / "core"))
import money  # noqa: E402
fails = []


def ok(c, m):
    print(("✅ " if c else "❌ ") + m)
    if not c:
        fails.append(m)


LONG = """Лира, результат чтения тестовой заметки принимаю как предварительный.

Теперь выполни только диагностику, без создания новых файлов.

Установи:
1. Полный физический путь к DEWIAR_LOCAL_TEST.md.md на диске Windows.
3. Какой конкретно инструмент создал файл.
4. Почему получилось двойное расширение .md.md."""
ok(money.parse(LONG) is None, "письмо в несколько строк — не вопрос о деньгах (ответит модель)")
ok(money.parse("Какой файл получился в итоге?") is None, "«получился» — не «получил»")
ok(money.parse(" ".join(["слово"] * 31) + " сколько я потратил") is None, "длиннее 30 слов — не к быстрым деньгам")
q = money.parse("сколько я получил в этом месяце") or {}
ok(q.get("op") == "query" and q.get("kind") == "income", "«сколько я получил в этом месяце» — по-прежнему вопрос о доходах")
q = money.parse("сколько я потратил на продукты") or {}
ok(q.get("op") == "query" and q.get("kind") == "expense", "«сколько я потратил на продукты» — по-прежнему без модели")
a = money.parse("потратил 500 рублей на такси") or {}
ok(a.get("op") == "add" and a.get("amount") == 500, "запись расхода — как раньше")
print("\nИТОГ:", "всё прошло" if not fails else f"провалов {len(fails)}")
sys.exit(1 if fails else 0)
