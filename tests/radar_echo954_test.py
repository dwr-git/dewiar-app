"""№954 (22.11, Роман): «задвоение предложений в сообщениях, отправляемых в мессенджер из „Радар: важное“ — лишние токены,
достаточно заголовка». Суть без предложений, которые пересказывают заголовок; новое в сути — остаётся."""
import sys
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "core"))
import insight as I  # noqa: E402
fails = []


def ok(c, m):
    print(("✅ " if c else "❌ ") + m)
    if not c:
        fails.append(m)


t = "Количество европейских наемников на Украине сокращается — Алаудинов"
s = ("Количество европейских наемников на Украине сокращается, сообщил командир спецназа «Ахмат». Это важно для ниши, так как "
     "указывает на изменение динамики.")
r = I.no_echo(t, s)
ok(r.startswith("Это важно") and "Количество" not in r, f"пересказ заголовка убран, новое осталось: {r!r}")
ok(I.no_echo("Истребитель F-35A повреждён над Ормузским проливом", "Истребитель F-35A повреждён над Ормузским проливом.") == "",
   "суть — только заголовок другими словами — пусто, в сообщении будет один заголовок")
ok(I.no_echo("Утечка исходников PHP", "Злоумышленники выложили 2 ГБ кода; патч ожидается в пятницу.") ==
   "Злоумышленники выложили 2 ГБ кода; патч ожидается в пятницу.", "суть, не повторяющая заголовок, — целиком")
src = (ROOT / "core/engine_insight.py").read_text(encoding="utf-8")
ok('top = dict(top, text=I.no_echo(top["title"], top.get("text") or ""))' in src and 'if top["text"] else top["title"]' in src,
   "«Радар: важное» в весточке и мессенджере — заголовок и только новое из сути")
print("ИТОГ:", "всё прошло" if not fails else f"провалов {len(fails)}")
sys.exit(1 if fails else 0)
