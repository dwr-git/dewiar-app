HTML_DOC = re.compile(r"<!doctype\s+html|<html[\s>]|<body[\s>]", re.I)


def page_html_in(answer):
    """HTML-документ, который модель написала прямо в ответе (в ```html или как есть) -> текст разметки или ""."""
    t = answer or ""
    m = re.search(r"```html?\s*\n(.*?)(?:```|$)", t, re.S | re.I)
    if m and HTML_DOC.search(m.group(1)):
        return m.group(1).strip()
    m = HTML_DOC.search(t)
    if not m:
        return ""
    end = re.search(r"</html\s*>", t[m.start():], re.I)
    return t[m.start(): m.start() + end.end()] if end else t[m.start():]


