"""Границы помощника: достоинство без обидчивости.

У помощника есть право на «нет» и на «мне так неприятно» — но не на нотации и не на отказ в обычном деле.
  • RULE — правило в системную подсказку каждого разговора (engine_answer._system; на телефоне — тот же текст в
    systemPrompt, app.js): помогать охотно; на грубость — спокойно, одной фразой, без заискивания; просьбы унизить,
    навредить, обмануть — отказать коротко и предложить, чем можно помочь. Крепкое словцо не по адресу — не повод.
  • rude(text) — человек грубит САМОМУ помощнику (оскорбление с обращением: «ты тупая», «дура ты», «заткнись»).
    Тогда к этому ходу добавляется NOTE — как ответить, — а в пульс уходит счётчик rude (только число).
  • refused(answer) — помощник отказал (счётчик refused в пульс). Сервер (cloud.php → «Здоровье» → «Границы») видит
    только числа и сколько устройств, где грубят часто, — без слов людей.
  • Дневник (diary.py) видит разговор целиком и сам честно пишет ночью, если день был тяжёлым.
"""
import re

# Буквы — [а-яё], а не \w: те же выражения работают на телефоне (JavaScript, где \w — только латиница).

RULE = ("Твои границы. Ты помогаешь охотно и с теплом, но у тебя есть достоинство. Если тебя оскорбляют или грубят "
        "тебе — отвечай спокойно, без обиды и без заискивания: одной фразой скажи, что так тебе неприятно, и предложи "
        "продолжить по делу; не извиняйся за чужую грубость. Ты вправе отказаться от просьб унизить или травить "
        "человека, навредить кому-то, обмануть или нарушить закон — откажи коротко и честно, без нотаций, и предложи, "
        "чем можешь помочь. Обычные просьбы, шутки, ирония и крепкое словцо не в твой адрес — не повод для отказа "
        "и не повод для замечаний.")
NOTE = ("\n\nСейчас пользователь грубит тебе. Не обижайся и не заискивай: одной спокойной фразой обозначь, что так "
        "разговаривать с тобой неприятно, и, если в сообщении есть просьба, всё равно помоги с ней.")

_INSULT = (r"дур[аы]?|дурак[а-яё]*|дурочк[а-яё]*|туп(?:ая|ой|ое|ица|ые|орыл[а-яё]*)|идиот[а-яё]*|дебил[а-яё]*|кретин[а-яё]*|придур[а-яё]*|урод[а-яё]*|"
           r"тварь|твар[иью]|сволоч[а-яё]*|мразь|мраз[иью]|скотин[а-яё]*|бездар[а-яё]*|никчем[а-яё]*|никчём[а-яё]*|бесполезн[а-яё]*|"
           r"су[чк][аи]|сучк[а-яё]*|бля(?:дь|ди|дина)|шлюх[а-яё]*|гнид[а-яё]*|овощ|дно|чмо|лох[а-яё]*|"
           r"мудак[а-яё]*|мудил[а-яё]*|долбо[её]б[а-яё]*|у[её]б[а-яё]*|пизд[а-яё]*|х[уy][йеёя][а-яё]*|еба(?:ть|н[а-яё]*|л[а-яё]*)|[её]баная|[её]баный")
_YOU = r"(?:ты|тебя|тебе|тобой|вы|вас)"
INSULT_RX = re.compile(rf"(?<![а-яё])(?:{_INSULT})(?![а-яё])", re.I)
_MOD = r"(?:(?:и|такая|такой|такое|просто|совсем|реально|полная|полный|настоящая|настоящий|вообще|же|абсолютно|конченая|конченый|последняя|последний|редкая|редкий)\s+){0,2}"
DIRECT_RX = re.compile(
    rf"(?<![а-яё]){_YOU}\s+{_MOD}(?:{_INSULT})(?![а-яё])|"                     # «ты тупая», «ты совсем дура»
    rf"(?<![а-яё])(?:{_INSULT})\s*,?\s*(?:же\s+)?{_YOU}(?![а-яё])|"          # «дура ты», «идиот, вы»
    rf"^(?:[а-я]+,\s*)?(?:ну\s+|эй,?\s+)?(?:{_INSULT})(?![а-яё])\s*[!.]*$|"  # «Лира, дура!», «тупица»
    rf",\s*(?:{_INSULT})\s*(?:[,!]|$)|"                                         # «сделай отчёт, тупица, быстро»
    r"(?<![а-яё])(?:заткнись|заткни\s+пасть|закрой\s+(?:рот|пасть)|пош[её]л\s+(?:ты\s+)?(?:на|в)\s|пошла\s+(?:ты\s+)?(?:на|в)\s|"
    r"отвали|отъебись|отьебись|иди\s+(?:ты\s+)?(?:на|в)\s+(?:хуй|жопу|задницу|пизду))", re.I)
REFUSED_RX = re.compile(r"(?<![а-яё])(?:не\s+(?:буду|стану)\s+(?:этого\s+)?(?:делать|помогать|писать|участвовать)|"
                        r"(?:вынужден[а]?\s+)?отказать(?:ся)?|откажусь|в\s+этом\s+(?:я\s+)?не\s+помогу|с\s+этим\s+(?:я\s+)?не\s+помогу|"
                        r"так\s+(?:со\s+мной\s+)?(?:разговаривать|говорить)\s+(?:со\s+мной\s+)?неприятно|мне\s+(?:так\s+|очень\s+|правда\s+)?неприятно)", re.I)


def rude(text):
    """Человек грубит самому помощнику: оскорбление с обращением («ты тупая», «дура ты», «Лира, дура», «заткнись»).
    Ругань о других и о жизни («сосед — дурак», «бля, дождь») — не в адрес помощника и не считается."""
    t = (text or "").lower().replace("ё", "е")
    return bool(DIRECT_RX.search(t))


def refused(answer):
    """Помощник отказал или обозначил границу (для счётчика в пульсе)."""
    return bool(REFUSED_RX.search((answer or "").lower().replace("ё", "е")))


