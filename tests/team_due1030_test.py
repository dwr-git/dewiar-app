"""Срок поручения словами (30.10, владелец: «ставлю поручение — что ни пиши, не понимает срок»: «сегодня до 24 часов»).
«до конца дня», «до полуночи», «до 24 часов» — сегодня 23:59; «до 18», «к 18 часам», «до 18 часов» — в 18:00; «до вечера»,
«до обеда», «до утра», «в течение часа»; «сегодня» вечером — до конца дня; прошедшее «сегодня до 18» — честно «уже прошло»."""
import os, sys
from datetime import datetime
from pathlib import Path
ROOT = Path(os.environ.get("DEWIAR_ROOT") or Path(__file__).resolve().parent.parent)
sys.path.insert(0, str(ROOT / "core"))
from team import due_parse  # noqa: E402
fails = []


def ok(c, m):
    print(("✅ " if c else "❌ ") + m)
    if not c:
        fails.append(m)


EVE, MOR = datetime(2026, 10, 30, 19, 6), datetime(2026, 10, 30, 11, 0)
D = lambda t, now: (due_parse(t, now)[0] or "нет").__str__()[:16]
for t, now, want in [("сегодня до 24 часов", EVE, "2026-10-30 23:59"), ("до 24 часов", EVE, "2026-10-30 23:59"), ("до конца дня", EVE, "2026-10-30 23:59"),
                     ("сегодня до полуночи", EVE, "2026-10-30 23:59"), ("в течение дня", MOR, "2026-10-30 23:59"), ("сегодня", EVE, "2026-10-30 23:59"),
                     ("сегодня", MOR, "2026-10-30 18:00"), ("сегодня до 18", MOR, "2026-10-30 18:00"), ("к 18 часам", MOR, "2026-10-30 18:00"),
                     ("до 18 часов", MOR, "2026-10-30 18:00"), ("сегодня до 18:00", MOR, "2026-10-30 18:00"), ("до вечера", MOR, "2026-10-30 18:00"),
                     ("завтра до обеда", MOR, "2026-10-31 13:00"), ("до утра", EVE, "2026-10-31 09:00"), ("в течение часа", MOR, "2026-10-30 12:00"),
                     ("к 21", EVE, "2026-10-30 21:00"), ("до 5 ноября", MOR, "2026-11-05 18:00"), ("до понедельника", MOR, "2026-11-02 18:00"),
                     ("завтра к 12", MOR, "2026-10-31 12:00"), ("до 7 вечера", MOR, "2026-10-30 19:00"), ("сегодня до 18", EVE, "нет")]:
    got = D(t, now)
    ok(got == want, f"«{t}» в {now:%H:%M} → {got}")
src = (ROOT / "core/team.py").read_text(encoding="utf-8")
ok("сегодня уже прошёл" in src, "прошедший срок сегодня — понятное «уже прошёл», а не «не поняла»")
print("\nИТОГ:", "всё прошло" if not fails else f"провалов {len(fails)}")
sys.exit(1 if fails else 0)
