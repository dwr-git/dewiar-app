"""Эмоции в голосе (19.11, владелец: «а ещё эмоций нет… ДА ДА ДА!!!»). Тон каждой фразы ответа — по её словам и по
настроению вопроса: радость за человека, сочувствие, шутка, удивление, спокойная серьёзность; иначе — свой обычный
тёплый голос (без указаний). Без модели и без лишнего в подсказке: решают слова — быстро и предсказуемо.

Куда тон идёт:
- голос Dewiar из облака (Qwen3-TTS) — указание манеры на фразу («instruct»: так и задумано у модели);
- остальные голоса (Piper, Vosk, Windows) — лишь чуть темп: радость живее, сочувствие спокойнее;
- лицо в виджете — улыбка после радостной фразы и шутки, без случайных улыбок при сочувствии (событие «tone»).

Не переигрывать: тон меняется только по ясному поводу, а «нейтральное» — это и есть обычный тёплый голос персонажа."""
import re

# указания манеры для Qwen3-TTS: по-английски модель понимает их лучше всего; коротко — длинное указание меняет тембр
INSTRUCT = {
    "joy": "Speak with genuine joy, bright and smiling.",
    "sympathy": "Speak softly and gently, with warm sympathy.",
    "playful": "Speak playfully, with a light smile in the voice.",
    "surprise": "Speak with lively, warm surprise.",
    "calm": "Speak calmly and seriously, unhurried.",
}
SPEED = {"joy": 1.04, "playful": 1.03, "surprise": 1.03, "sympathy": 0.94, "calm": 0.96}

_W = r"(?<![а-яё])"
SAD_RX = re.compile(_W + r"(?:умер|умерла|умерли|скончал|похорон|погиб|болею|заболел|болит|больно|плохо мне|мне плохо|грустн|"
                    r"тоскл|одинок|тяжело|устал[аи]?\b|депресс|плач|слёз|слез|расстав|бросил[аи]?\b|уволил|увольн|"
                    r"страшно|боюсь|тревож|переживаю|не спится|не могу уснуть|провалил|не получилось|потерял[аи]?\b|авари)", re.I)
JOY_Q_RX = re.compile(_W + r"(?:ура\b|получилось|сдал[аи]?\b|выиграл|победил|родил|поженил|свадьб|повысили|взяли на работу|"
                      r"купил[аи]? (?:машину|квартиру|дом)|день рождения|юбилей|праздник|отпуск|наконец-то)", re.I)
# «отлично, записала», «прекрасно, поставила» — обычные подтверждения, не повод для радости в голосе
JOY_RX = re.compile(_W + r"(?:поздравляю|поздравля|ура\b|как здорово|это здорово|здорово!|вот это успех|браво|"
                    r"молодец|умница|как я рада|как я рад|я так рада|я так рад|рада за|рад за)", re.I)
SYM_RX = re.compile(_W + r"(?:сочувствую|соболезн|мне (?:очень )?жаль|как (?:же )?(?:тяжело|грустно|обидно)|держитесь|"
                    r"берегите себя|понимаю, как|это непросто|вы не одн|обнимаю)", re.I)
PLAY_RX = re.compile(r"(?:\bшутк|анекдот|хаха|ха-ха|😄|😂|😉|😁|\bхи-хи|забавн|смешн)", re.I)
SURPRISE_RX = re.compile(_W + r"(?:ого\b|ух ты|вот это да|неужели|не может быть|надо же|вот так новость)", re.I)
CALM_RX = re.compile(_W + r"(?:осторожн|опасн|важно:|внимание|срочно|немедленно|обратитесь к врачу|вызовите скорую|"
                     r"не (?:стоит|советую|рекомендую)|будьте внимательн|предупрежда)", re.I)


def mood_of(asked):
    """Настроение вопроса -> "sad" | "joy" | None. Только начало (до вложений): о чём человек говорит сам."""
    t = str(asked or "").split("\n\nВложения:", 1)[0][:600].lower().replace("ё", "е")
    if SAD_RX.search(t):
        return "sad"
    if JOY_Q_RX.search(t):
        return "joy"
    return None


def tone_of(sentence, mood=None):
    """Тон фразы ответа -> ключ INSTRUCT или None (обычный голос). Грустный вопрос — весь ответ мягко, без шуток и
    восклицаний; иначе — по словам самой фразы."""
    s = str(sentence or "").lower().replace("ё", "е")
    if mood == "sad" or SYM_RX.search(s):
        return "sympathy"
    if CALM_RX.search(s):
        return "calm"
    if JOY_RX.search(s) or (mood == "joy" and "!" in s):
        return "joy"
    if PLAY_RX.search(s):
        return "playful"
    if SURPRISE_RX.search(s):
        return "surprise"
    return None


def speed_of(tone):
    return SPEED.get(tone or "", 1.0)
