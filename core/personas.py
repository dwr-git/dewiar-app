# Как произносить имена. В тексте ответа — «Девиар»/«Dewiar», в голос — правильное ударение
# «ДэвиАр». Локальные голоса (Piper, eSpeak) читают через eSpeak: «Дэвиаар» даёт ударение на «а»
# и чёткое «Дэ» (проверено по фонемам: dE2v;i'AVr). Нейросетевым голосам на сервере — знак ударения.
PRONOUNCE = [
    (re.compile(r"(?i)(?<![\w])(?:девиар|дэвиар|dewiar)"), "Дэвиаар", "Дэвиа\u0301р"),
    # 29.10, владелец: «пото́м, а не по́том» — eSpeak читает p'otVm; «потоом» даёт pVt'oVm (проверено по фонемам)
    (re.compile(r"(?<![\w])([Пп])отом(?![\w])"), r"\1отоом", "\\1ото\u0301м"),
]


def pronounce(text, remote=False):
    """Текст для синтеза речи: имя с правильным ударением. remote=True — для нейросетевых голосов сервера."""
    for rx, local, rem in PRONOUNCE:
        text = rx.sub(rem if remote else local, text)
    return text


