def _slug(name: str) -> str:
    tr = dict(zip("абвгдеёжзийклмнопрстуфхцчшщъыьэюя",
                  ["a", "b", "v", "g", "d", "e", "e", "zh", "z", "i", "y", "k", "l", "m", "n", "o", "p",
                   "r", "s", "t", "u", "f", "h", "c", "ch", "sh", "sch", "", "y", "", "e", "yu", "ya"]))
    s = "".join(tr.get(c, c) for c in name.lower())
    s = re.sub(r"[^a-z0-9]+", "-", s).strip("-")
    return s or "persona"


def migrate_names():
    """Однократный перенос (метка PERSONAS_DIR/.names-0.23): выученное произношение имени «Агент» (agent.heard.json)
    и голосовой отпечаток agent переходят к главному помощнику dewiar, чьё имя — «Агент». Прежний отпечаток
    dewiar откладывается в voiceprints-old; «девиар» остаётся среди aliases главного. Если пользователь сам
    переименовал agent — обучение остаётся у agent. Ошибки только пишутся в журнал."""
    import shutil
    mark = PERSONAS_DIR / ".names-0.23"
    if mark.exists() or not PERSONAS_DIR.exists() and not VOICEPRINT_DIR.exists():
        return
    try:
        agent_file = PERSONAS_DIR / "agent.json"
        if agent_file.exists():                       # пользователь сам переименовал «Агента» — его обучение остаётся ему
            try:
                nm = (json.loads(agent_file.read_text(encoding="utf-8")).get("name") or "").strip()
            except ValueError:
                nm = ""
            if nm and nm != RENAMED["agent"]:
                PERSONAS_DIR.mkdir(parents=True, exist_ok=True)
                mark.write_text("имя Агента изменено пользователем — обучение не переносилось\n", encoding="utf-8")
                return
        src, dst = PERSONAS_DIR / "agent.heard.json", PERSONAS_DIR / "dewiar.heard.json"
        if src.exists():
            a = json.loads(src.read_text(encoding="utf-8"))
            b = json.loads(dst.read_text(encoding="utf-8")) if dst.exists() else {}
            for k, v in a.items():
                b[k] = sorted(set(b.get(k) or []) | set(v or []))
            dst.write_text(json.dumps(b, ensure_ascii=False, indent=1), encoding="utf-8")
            src.unlink()
        va, vd = VOICEPRINT_DIR / "agent", VOICEPRINT_DIR / "dewiar"
        if va.is_dir():
            if vd.is_dir():
                old = STATE_DIR / "voiceprints-old"
                old.mkdir(parents=True, exist_ok=True)
                shutil.rmtree(old / "dewiar", ignore_errors=True)
                shutil.move(str(vd), str(old / "dewiar"))
            shutil.move(str(va), str(vd))
        PERSONAS_DIR.mkdir(parents=True, exist_ok=True)
        mark.write_text("Девиар → Агент, Агент → Кодер\n", encoding="utf-8")
    except (OSError, ValueError) as e:
        log.warning("Перенос выученных имён не удался: %s", e)


def migrate_templates():
    """Однократно (метка PERSONAS_DIR/.templates-0.36): Агент, Джарвис, Эва и Кодер стали шаблонами. Кто ими
    пользовался — выбран в настройках, учил имя («Научить произношению»), менял фото или текст — получает его своим
    персонажем с тем же id: файл PERSONAS_DIR/<id>.json с меткой template (поля дополняются из шаблона при загрузке),
    поэтому настройки, голосовой отпечаток, выученное произношение и история остаются. Ошибки только в журнал."""
    mark = PERSONAS_DIR / ".templates-0.36"
    if mark.exists():
        return
    try:
        cur = ""
        try:
            cur = json.loads(SETTINGS_PATH.read_text(encoding="utf-8")).get("persona") or ""
        except (OSError, ValueError):
            pass
        kept = []
        for pid in TEMPLATES:
            f = PERSONAS_DIR / f"{pid}.json"
            used = (cur == pid or f.exists() or (PERSONAS_DIR / f"{pid}.heard.json").exists()
                    or (VOICEPRINT_DIR / pid / "meta.json").exists() or any(PERSONAS_DIR.glob(f"{pid}.avatar.*")))
            if not used:
                continue
            data = {}
            if f.exists():
                try:
                    data = json.loads(f.read_text(encoding="utf-8"))
                except ValueError:
                    data = {}
            data["template"] = True
            PERSONAS_DIR.mkdir(parents=True, exist_ok=True)
            f.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")
            kept.append(pid)
        PERSONAS_DIR.mkdir(parents=True, exist_ok=True)
        mark.write_text("шаблонами стали: " + ", ".join(TEMPLATES) + "; остались своими: " + (", ".join(kept) or "никто") + "\n",
                        encoding="utf-8")
        if kept:
            log.info("Персонажи стали шаблонами; у вас остаются своими: %s", ", ".join(kept))
    except OSError as e:
        log.warning("Перенос персонажей в шаблоны не удался: %s", e)


class Personas:
    def __init__(self):
        self._lock = threading.RLock()
        self.items = {}
        migrate_names()
        migrate_templates()
        self.reload()

    def reload(self):
        """Собрать self.items: встроенные, поверх — файлы PERSONAS_DIR (без прежних заводских текстов, см. OLD_DEFAULTS
        и RENAMED), затем выученное произношение *.heard.json. В конце у каждого остаются только те aliases и heard,
        которые не совпадают со словом запуска другого персонажа."""
        with self._lock:
            items = {k: dict(copy.deepcopy(v), id=k, builtin=True) for k, v in BUILTIN.items()}
            if PERSONAS_DIR.exists():
                for f in sorted(PERSONAS_DIR.glob("*.json")):
                    if f.name.endswith(".heard.json"):
                        continue
                    try:
                        p = json.loads(f.read_text(encoding="utf-8"))
                        pid = f.stem
                        olds = OLD_DEFAULTS.get(pid) or {}
                        for od in olds if isinstance(olds, list) else [olds]:
                            for k, v in od.items():
                                if p.get(k) == v:
                                    p.pop(k)
                        if pid in RENAMED and (p.get("name") or "").strip() == RENAMED[pid]:
                            for k in ("name", "wake", "aliases"):
                                p.pop(k, None)
                        # свой персонаж из шаблона (бывший встроенный или из «Готовых») — недостающие поля из шаблона:
                        # живое лицо, главная роль, маршрут к специалисту не теряются
                        base = items.get(pid) or copy.deepcopy(TEMPLATES.get(pid) or (GALLERY.get(pid) if p.get("gallery") else None) or {})
                        p = dict(base, **p, id=pid, builtin=pid in BUILTIN)
                        p.setdefault("aliases", [w for w in p.get("wake", [])])
                        items[pid] = p
                    except (OSError, json.JSONDecodeError) as e:
                        log.warning("Не удалось прочитать персонажа %s: %s", f, e)
                # как распознаватели слышат имя голосом владельца («Научить произношению»)
                for f in sorted(PERSONAS_DIR.glob("*.heard.json")):
                    pid = f.name[:-len(".heard.json")]
                    if pid not in items:
                        continue
                    try:
                        heard = json.loads(f.read_text(encoding="utf-8"))
                        items[pid]["heard"] = heard
                        extra = {w for ws in heard.values() for w in ws}
                        items[pid]["aliases"] = sorted(set(items[pid].get("aliases") or []) | extra)
                    except (OSError, json.JSONDecodeError) as e:
                        log.warning("Не удалось прочитать персонажа %s: %s", f, e)
            # имя одного не должно будить другого (например, выученное «как слышится» от прежнего имени)
            own = {}
            for pid, p in items.items():
                for w in p.get("wake") or []:
                    own.setdefault(w.lower(), pid)
            for pid, p in items.items():
                p["aliases"] = [a for a in p.get("aliases") or [] if own.get(a.lower(), pid) == pid]
                if p.get("heard"):
                    p["heard"] = {k: [w for w in v if own.get(str(w).lower(), pid) == pid] for k, v in p["heard"].items()}
            self.items = items

    def get(self, pid):
        """Копия персонажа; неизвестный id — Лира (главная)."""
        with self._lock:
            return copy.deepcopy(self.items.get(pid) or self.items[DEFAULT])

    def all(self):
        with self._lock:
            return [copy.deepcopy(p) for p in self.items.values()]

    def public(self):
        """Для интерфейса: вместо avatar (имя файла) — avatar_url (картинка как data-URL); taught — есть ли голосовой
        отпечаток («Научить произношению»)."""
        out = []
        for p in self.all():
            q = {k: v for k, v in p.items() if k != "avatar"}
            q["avatar_url"] = self.avatar_data_url(p)
            if p.get("avatar") and (PERSONAS_DIR / p["avatar"]).exists():
                q.pop("live", None)                   # своё фото вместо портрета — живое лицо Эвы не рисуем
            q["taught"] = (VOICEPRINT_DIR / p["id"] / "meta.json").exists()
            out.append(q)
        return out

    def avatar_data_url(self, p):
        """Своё фото персонажа, иначе портрет из комплекта (AVATARS_DIR/<id>.*), иначе ""."""
        name = p.get("avatar")
        path = PERSONAS_DIR / name if name else None
        if path is None or not path.exists():
            path = next((AVATARS_DIR / f"{p.get('id')}{ext}" for ext in (".png", ".webp", ".jpg")
                         if (AVATARS_DIR / f"{p.get('id')}{ext}").exists()), None)    # портрет из комплекта
        if path is None:
            return ""
        mime = {".png": "image/png", ".webp": "image/webp", ".gif": "image/gif"}.get(path.suffix, "image/jpeg")
        return f"data:{mime};base64," + base64.b64encode(path.read_bytes()).decode()

    def save(self, p: dict) -> str:
        """Создать или изменить персонажа -> id. Новому персонажу id делается из имени (с суффиксом -2, -3… при совпадении).
        p может содержать avatar_data (data-URL загруженного фото, до 6 МБ — пишется в <id>.avatar.*).
        Пишет PERSONAS_DIR/<id>.json и перечитывает всех; ValueError — без имени или слишком большое фото."""
        with self._lock:
            PERSONAS_DIR.mkdir(parents=True, exist_ok=True)
            name = (p.get("name") or "").strip()
            if not name:
                raise ValueError("У персонажа должно быть имя")
            pid = p.get("id") or _slug(name)
            if not p.get("id"):
                base, n = pid, 2
                while pid in self.items:
                    pid, n = f"{base}-{n}", n + 1
            keep = {k: p[k] for k in ("name", "gender", "wake", "style", "color", "tagline", "about",
                                      "character", "voice", "role", "skills", "focus", "route", "gallery", "knowledge", "template") if k in p}
            if pid in TEMPLATES and pid in self.items:
                keep["template"] = True                # свой из шаблона: живое лицо и роль — из шаблона (reload)
            if "knowledge" in keep:                    # базы сайта Dewiar, по которым персонаж отвечает
                # и папки на этом компьютере (YouTube 27.10: «знания только с сервера, а если работаю локально?») —
                # kind "folder", path; ищутся локально (knowledge.py), без входа в аккаунт
                keep["knowledge"] = [{k: str(b[k]) for k in ("kind", "id", "label", "lib", "path") if b.get(k)}
                                     for b in keep["knowledge"] or [] if isinstance(b, dict) and b.get("kind")
                                     and (b.get("id") or (b.get("kind") == "folder" and b.get("path")))][:6]
            elif pid in self.items and self.items[pid].get("knowledge"):
                keep["knowledge"] = self.items[pid]["knowledge"]
            keep["wake"] = [w.strip().lower() for w in keep.get("wake") or [name] if w.strip()]
            keep["aliases"] = sorted(set(keep["wake"]))
            data_url = p.get("avatar_data") or ""
            if data_url.startswith("data:image/"):
                header, b64 = data_url.split(",", 1)
                ext = ".png" if "png" in header else ".webp" if "webp" in header else ".gif" if "gif" in header else ".jpg"
                raw = base64.b64decode(b64)
                if len(raw) > 6 * 1024 * 1024:
                    raise ValueError("Картинка больше 6 МБ — уменьшите её")
                for old in PERSONAS_DIR.glob(f"{pid}.avatar.*"):
                    old.unlink()
                (PERSONAS_DIR / f"{pid}.avatar{ext}").write_bytes(raw)
                keep["avatar"] = f"{pid}.avatar{ext}"
                keep.setdefault("style", "photo")
            elif p.get("avatar") is not None:
                keep["avatar"] = p.get("avatar")
            elif pid in self.items and self.items[pid].get("avatar"):
                keep["avatar"] = self.items[pid]["avatar"]
            (PERSONAS_DIR / f"{pid}.json").write_text(json.dumps(keep, ensure_ascii=False, indent=2),
                                                     encoding="utf-8")
            self.reload()
            return pid

    @staticmethod
    def fixed_ids():
        """id встроенных, шаблонов и галереи — их между устройствами не синхронизируем (у каждого свой комплект)."""
        return set(BUILTIN) | set(TEMPLATES) | set(GALLERY)

    def own_ids(self):
        """Свои персонажи (созданы человеком здесь или пришли с телефона) — их синхронизация переносит между устройствами."""
        fixed = self.fixed_ids()
        return {pid for pid in self.items if pid not in fixed and not self.items[pid].get("gallery")}

    def delete(self, pid):
        """Свой персонаж удаляется, встроенный сбрасывается к заводскому (вместе с фото и выученным произношением)."""
        with self._lock:
            for f in list(PERSONAS_DIR.glob(f"{pid}.json")) + list(PERSONAS_DIR.glob(f"{pid}.avatar.*")) + \
                    list(PERSONAS_DIR.glob(f"{pid}.heard.json")):
                f.unlink()
            self.reload()

    def gallery(self):
        """Готовые персонажи: шаблоны (бывшие встроенные) и специалисты. installed — уже в команде."""
        have = set(self.items)
        src = list(TEMPLATES.items()) + [(k, v) for k, v in GALLERY.items() if not v.get("kids")]
        return [dict(copy.deepcopy(v), id=k, installed=k in have, template=k in TEMPLATES, avatar_url=self.avatar_data_url({"id": k}))
                for k, v in src]

    def gallery_add(self, gid):
        if gid in TEMPLATES:                          # бывший встроенный — своим, поля дополнятся из шаблона (reload)
            with self._lock:
                PERSONAS_DIR.mkdir(parents=True, exist_ok=True)
                (PERSONAS_DIR / f"{gid}.json").write_text(json.dumps({"template": True}, ensure_ascii=False), encoding="utf-8")
                self.reload()
            return gid
        g = GALLERY.get(gid)
        if not g:
            raise ValueError("нет такого специалиста")
        return self.save(dict(copy.deepcopy(g), id=gid, gallery=True))

    def wake_map(self, only=None):
        """Слово запуска -> id персонажа: wake плюс то, как имя слышит маленький распознаватель Vosk (heard["vosk"]).
        only — только для одного персонажа."""
        out = {}
        for p in self.all():
            if only and p["id"] != only:
                continue
            for w in list(p.get("wake", [])) + list((p.get("heard") or {}).get("vosk", [])):
                out[w.lower()] = p["id"]
        return out

    def set_heard(self, pid, heard):
        with self._lock:
            PERSONAS_DIR.mkdir(parents=True, exist_ok=True)
            f = PERSONAS_DIR / f"{pid}.heard.json"
            if heard:
                f.write_text(json.dumps(heard, ensure_ascii=False, indent=1), encoding="utf-8")
            elif f.exists():
                f.unlink()
            self.reload()

    def system_prompt(self, pid, user_name="", now_str=""):
        """Системная подсказка: характер, правило рода (gender.py), роль, VOICE_RULES, состав команды, имя собеседника
        и текущее время."""
        p =self.get(pid)
        others = [q for q in self.all() if q["id"] != pid]
        roster = "; ".join(f"{q['name']} — {q['role'].lower()}" if q.get("role") else q["name"] for q in others)
        team = (f"Ты — один из команды помощников этой программы. Команда: {roster}. Пользователь может звать любого "
                "по имени посреди разговора. Разговор пользователя с коллегой приходит тебе справкой «[До этого пользователь "
                "говорил не с тобой, а с коллегой…]»: это их разговор — не продолжай его и не отвечай за коллегу, пока "
                "пользователь сам об этом не попросит; отвечай на то, что он говорит тебе. Если просят то, в чём коллега сильнее, "
                "можешь ответить сам или позвать его (call_persona) — по ситуации.") if others else ""
        from gender import prompt_rule
        parts = [p.get("character", ""), TALK_RULES, prompt_rule(p.get("gender")), p.get("focus", ""), VOICE_RULES, team]
        if user_name:
            parts.append(f"Собеседника зовут {user_name}.")
        if now_str:
            parts.append(f"Сейчас {now_str}.")
        return "\n\n".join(x for x in parts if x)
