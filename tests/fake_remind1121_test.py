"""Владелец 21.11, 21:08 (скриншот): в 19:26 «напомни через 2 часа…» — поставлено без модели на 21:26. В 21:08 приветствие
«С возвращением»: «Напоминание… уже поставила на 21:26» (правда) — и следом «⚠ На самом деле напоминание не поставлено — модель
не вызвала инструмент». Проверка «сказала, что поставила» не относится к служебным поручениям (приветствие, дело по
расписанию) и сверяется со списком напоминаний: время, на которое правда стоит напоминание, — не выдумка."""
import os, sys
from pathlib import Path
from types import SimpleNamespace
ROOT = Path(os.environ.get("DEWIAR_ROOT") or Path(__file__).resolve().parent.parent)
sys.path.insert(0, str(ROOT / "core"))
fails = []


def ok(c, m):
    print(("✅ " if c else "❌ ") + m)
    if not c:
        fails.append(m)


import engine_brain as EB  # noqa: E402

e = EB.BrainMixin.__new__(EB.BrainMixin)
e.reminders = SimpleNamespace(items=[{"id": 1, "at": "2026-11-21T21:26:00", "text": "Проверить движок VLM"}])
T = lambda full, **k: SimpleNamespace(full=full, tools_ok=[], **k)   # noqa: E731
f = EB.BrainMixin._fake_reminder
ok(f(e, "👋 С возвращением. Напомни человеку о делах…", T("С возвращением! Напоминание уже поставила на 21:26.", greet=True)) == "",
   "приветствие — служебное поручение: не проверяем")
ok(f(e, "напомни проверить движок", T("Напоминание уже стоит на 21:26.")) == "", "называет время, на которое правда стоит напоминание, — правда")
ok(f(e, "напомни позвонить маме в 18:00", T("Готово, напомню в 18:00.")).startswith("⚠"), "напоминания на это время нет, а «напомню» — предупреждаем, как раньше")
ok(f(e, "напомни позвонить маме", T("Хорошо, поставила.", raw=True)) == "", "дело по расписанию — тоже служебное")
print("ИТОГ:", "всё прошло" if not fails else f"{len(fails)} не прошло")
sys.exit(1 if fails else 0)
