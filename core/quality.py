_WAIT = r"(?:одну\s+)?(?:секунд\w*|секундочк\w*|минутк\w*|минуточк\w*|мгновени\w*|сейчас|подожд\w*|момент\w*)"
PROMISE_NOW = re.compile(rf"\b{_NOW}\b[^.!?]*\b{_WAIT}\b|\b{_WAIT}\b[^.!?]*\b{_NOW}\b", re.I)
# «Сейчас, вот они — календарь и напоминания.» (отчёт 14.10) — «вот они», а показать нечего: короткий ответ без цифр
SHOW_EMPTY = re.compile(r"^\W*(?:(?:сейчас|секунду|минутку|хорошо|конечно|да|итак)[,.!\s—–-]*)*вот\s+(?:он[аио]?|они|всё|все)\b", re.I)


def looks_like_promise(text):
    """Короткий ответ-обещание без результата («сейчас посмотрю… и расскажу», «достаю календарь — одну секунду»)."""
    t = (text or "").strip()
    m = SHOW_EMPTY.search(t) if 0 < len(t) <= 160 and not re.search(r"\d", t) else None
    if m and ":" not in t[m.end():] and len(t) - m.end() < 60:     # «вот они — календарь» без самого списка
        return True
    return 0 < len(t) <= 400 and not t.endswith("?") and bool(PROMISE.search(t) or PROMISE_NOW.search(t))


