"""«Ум Лиры», шаг 2 — ворота внимания, первое: без шума от руководства. Экзамен владельца 20.11: к вопросам «два варианта
ужина», «световой день», «15 % от 2400», «как начать отчёт», «прививка собаке», «по-английски „вчера“» прикладывался
случайный раздел руководства (два совпавших слова) — лишние сотни токенов и чужая тема в справке к вопросу. Теперь раздел
руководства — только к вопросам о самом приложении (его слова, «у тебя», название раздела в кавычках)."""
import os, sys
from pathlib import Path
ROOT = Path(os.environ.get("DEWIAR_ROOT") or Path(__file__).resolve().parent.parent)
sys.path.insert(0, str(ROOT / "core"))
import guide  # noqa: E402

bad = 0


def ok(c, m):
    global bad
    bad += 0 if c else 1
    print(("✅ " if c else "❌ ") + m)


def g(q):
    return guide.attach(q, "pc") or guide.hint(q, "pc")


noise = ["Предложи два варианта ужина на сегодня: что-нибудь с пастой и какой-нибудь суп. Коротко, по одной строке.",
         "Кстати, сколько сейчас длится световой день примерно?",
         "Хочу съездить на выходные в Казань вдвоём. Составь короткий план: где жить и что посмотреть. Бюджет я уточню позже.",
         "Подожди, пока не забыл: как будет по-английски «вчера»?", "Спасибо. И сколько будет 15 процентов от 2400?",
         "Как коротко начать отчёт о работе за месяц? Одну фразу.", "Понял. А ей когда обычно делают прививку от бешенства — раз в год?"]
for q in noise:
    ok(not g(q), f"без руководства: «{q[:50]}»")
app = {"А как у тебя защищены мои персональные данные? Кто может читать наши разговоры?": "Ваши данные",
       "Что это за значки у меня в «Делах» — «Тройка», «Три дня подряд»? Зачем они?": "Дела и достижения",
       "на сколько хватает 1 талер?": "Талер", "пополнил счёт, ничего не пришло": "Талер",
       "как добавить маму в близкие?": "близк", "есть у тебя видеоуроки?": "урок"}
for q, want in app.items():
    ok(want.lower() in g(q).lower(), f"о приложении — раздел «{want}»: «{q[:45]}»")
print("ИТОГ:", "всё в порядке" if not bad else f"ошибок {bad}")
sys.exit(1 if bad else 0)
