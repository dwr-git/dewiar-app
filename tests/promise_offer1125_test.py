"""Стенд 25.11, pc_can («Что ты умеешь делать на компьютере? Коротко.»): список умений с предложением «Скажите, что сделать, —
сейчас сделаю» проверка принимала за обещание — дважды просила модель «сделай», и человек слышал «Простите, до дела так и не
дошло» на вопрос, где делать было нечего. Фраза, которая просит человека сказать, что делать, — предложение, а не обещание;
настоящее обещание («Сейчас сделаю», «Секунду, сейчас найду») ловится как прежде."""
import os, sys
from pathlib import Path
ROOT = Path(os.environ.get("DEWIAR_ROOT") or Path(__file__).resolve().parent.parent)
sys.path.insert(0, str(ROOT / "core"))
from quality_answer import looks_like_promise as L  # noqa: E402
fails = []


def ok(c, m):
    print(("✅ " if c else "❌ ") + m)
    c or fails.append(m)


q = "Что ты умеешь делать на компьютере? Коротко."
ok(not L("На компьютере я могу: напоминания, заметки, поиск в интернете, музыку, открыть программу или сайт. "
         "Скажите, что сделать — сейчас сделаю.", q), "умения + «скажите, что сделать — сейчас сделаю» — не обещание")
ok(not L("Напоминания, заметки, музыка и радио.\nНазовите, что нужно, — сейчас займусь.", q), "«назовите, что нужно, — займусь» с новой строки")
ok(L("Хорошо, сейчас сделаю. Скажите, если нужно что-то ещё.", "поставь будильник"), "обещание перед предложением — всё ещё обещание")
ok(L("Если хотите, сейчас сделаю напоминание.", "поставь напоминание"), "«если хотите, сейчас сделаю» в ответ на просьбу — обещание")
ok(L("Секунду, сейчас найду.", "найди погоду"), "«Секунду, сейчас найду» — обещание")
ok(L("Сейчас посмотрю, что я умею на этом компьютере, и расскажу.", q), "«сейчас посмотрю и расскажу» — обещание")
print("\nИТОГ:", "всё прошло" if not fails else f"провалов {len(fails)}")
print("ALL OK" if not fails else "")
sys.exit(1 if fails else 0)
