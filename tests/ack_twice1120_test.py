"""Экзамен владельца 20.11 (оба прогона): «Поняла, записала.» — remember — «Записала. Пять лет — уже образ жизни»: до действия
модель подтвердила, после — подтвердила снова. Теперь второе короткое подтверждение после действия срезается (и на экране,
и вслух), остальное говорится. Сказанное до действия — не подтверждение, или после — новое (погода, время) — как было."""
import os, sys
from pathlib import Path
ROOT = Path(os.environ.get("DEWIAR_ROOT") or Path(__file__).resolve().parent.parent)
sys.path.insert(0, str(ROOT / "core"))
from answer_rules import ack_again  # noqa: E402

bad = 0


def ok(c, m):
    global bad
    bad += 0 if c else 1
    print(("✅ " if c else "❌ ") + m)


def rest(a, b):
    c = ack_again(a, b, fin=True)
    return b[c:] if c else b


ok(rest("Поняла, записала.", " Записала. Пять лет — уже не диета, а образ жизни.") == "Пять лет — уже не диета, а образ жизни.", "второе «Записала.» — срезано, мысль осталась")
ok(rest("Записала.", " Запомнила.") == "", "«Записала.» + «Запомнила.» — одно")
ok(rest("Поняла, записала. Записала.", "Сочи: 15 градусов.") == "Сочи: 15 градусов.", "после — новое: как было")
ok(rest("Сейчас посмотрю.", "Записала.") == "Записала.", "до действия не подтверждали — подтверждение остаётся")
ok(rest("Поставила напоминание.", "Готово, напомню в 6:30.") == "Готово, напомню в 6:30.", "подтверждение с новым (время) — остаётся")
ok(ack_again("Записала.", " Запис") is None, "полслова — подождать")
src = (ROOT / "core/engine_answer.py").read_text(encoding="utf-8")
ok("cut = ack_again(turn.full, probe)" in src and "ack_seen = not probing" in src, "ход: срезается до показа и голоса")
print("ИТОГ:", "всё в порядке" if not bad else f"ошибок {bad}")
sys.exit(1 if bad else 0)
