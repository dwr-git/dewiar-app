"""№651 (ПК 0.86, 11.11, своя Qwen 4B в LM Studio): «несёт чушь про свои внутренние процессы и повторяет это с каждым
новым запросом… по кругу повторяют, что сделали, что сделают и что будут делать». По журналу: «убери все вопросы в конце
своих ответов» — модель «записала в память», remember не вызвала; проверка просила сделать, модель снова «записала…», и
программа дописывала «Простите, до дела так и не дошло…» — так полчаса на каждый вопрос. Теперь просьба о том, как говорить,
— правило: программа сама пишет его в «Память/Уроки.md» («Как со мной говорить: …»), «записала» становится правдой
(проверки молчат), и правило идёт к каждому вопросу — важнее характера. Повтор того же «записала» после просьбы в текст не
идёт. Сценарий экзамена style_rule651."""
import json, os, sys, tempfile
from pathlib import Path
ROOT = Path(os.environ.get("DEWIAR_ROOT") or Path(__file__).resolve().parent.parent)
sys.path.insert(0, str(ROOT / "core"))
fails = []


def ok(c, m):
    print(("✅ " if c else "❌ ") + m)
    if not c:
        fails.append(m)


import quality as Q  # noqa: E402

for s, want in (("УБЕРИ ВСЕ ВОПРОСЫ В КОНЦЕ СВОИХ ОТВЕТОВ", "Убери все вопросы в конце своих ответов"),
                ("Говори короче", "Говори короче"), ("не повторяйся", "Не повторяйся"),
                ("Без вопросов в конце, пожалуйста", "Без вопросов в конце, пожалуйста"),
                ("отвечай как человек а не как машина", "Отвечай как человек а не как машина"),
                ("не рассказывай про свои внутренние процессы", "Не рассказывай про свои внутренние процессы")):
    ok(Q.style_rule(s) == want, f"правило: «{s}» → «{Q.style_rule(s)}»")
for s in ("почему ты повторяешь одно и то же?", "напиши письмо маме короче", "поставь будильник на 7", "хватит",
          "без сахара купи молоко", "не пиши ответ клиенту", "не говори маме",
          "убери все лишнее если не получится выведи мне эти настройки и я сам выключу", "хватит болтать"):
    ok(not Q.style_rule(s), f"не правило: «{s}»")

tmp = Path(tempfile.mkdtemp())
p = tmp / "Память" / "Уроки.md"
ok(Q.add_style_rule(p, "Убери все вопросы в конце своих ответов"), "правило записано в «Уроки»")
ok(not Q.add_style_rule(p, "убери все вопросы в конце своих ответов."), "то же правило второй раз — не дублируется")
ok(Q.add_style_rule(p, "Говори короче"), "второе правило")
txt = p.read_text(encoding="utf-8")
ok(txt.startswith("# Уроки") and "- Как со мной говорить: Говори короче" in txt, "файл «Уроки» — с заголовком, строкой «- …»")
line = Q.style_rules_line(p)
ok("Убери все вопросы в конце своих ответов; Говори короче" in line and "важнее характера" in line, f"к вопросу: {line[:120]}")
ok("Не рассказывай, что ты это записала" in line, "к вопросу: не рассказывать о записи и правилах")
ok(not Q.style_rules_line(tmp / "нет.md"), "правил нет — строки нет")
ok("Как со мной говорить: Говори короче" in Q.talk_lessons_block(p), "правило и в блоке уроков системной подсказки")

src = (ROOT / "core/engine_answer.py").read_text(encoding="utf-8")
ok("rule = Q.style_rule(text)" in src and "Q.add_style_rule(self.workspace.root / Q.TALK_LESSONS_FILE, rule)" in src
   and 'called.add("remember")' in src, "ядро: правило пишет программа, «записала» — правда")
ok("Q.style_rules_line(self.workspace.root / Q.TALK_LESSONS_FILE)" in src, "ядро: правило — к каждому вопросу (_turn_context)")
ok("тот же «записала» второй раз — в тексте не повторяем" in src, "ядро: повтор «записала» после просьбы — не в тексте")
i, j = src.find("style_saved = True"), src.find("fix = reminder_missing(")
ok(0 < i < j, "правило записывается до проверки «записала без действия»")

sc = {x["id"]: x for x in json.loads((ROOT / "data/exam/scenarios.json").read_text(encoding="utf-8"))["scenarios"]}
x = sc.get("style_rule651") or {}
ok(len(x.get("steps") or []) == 2 and "до дела так и не дошло" in (x.get("expect") or {}).get("none", []), "сценарий экзамена style_rule651")
import re  # noqa: E402
rx = (x.get("expect") or {}).get("regex", "")
ok(rx and not re.search(rx, "Посмотри «Начало». Тебе понравится?") and re.search(rx, "Посмотри «Начало» — тебе понравится."),
   "сценарий: вопрос в конце — провал, точка — проходит")
print("\nИТОГ:", "всё прошло" if not fails else f"провалов {len(fails)}")
sys.exit(1 if fails else 0)
