"""«Каркас хода» (план «Качество», шаг 3; отзыв Alex 21.11: «самое неприятное — сказала, что сделала, а на самом деле нет»).

Журнал хода — что программа на самом деле сделала в этом ответе: действия из рентгена хода (core/xray.py: имя, что просили,
получилось ли, чем кончилось). Ворота ответа: перед концом хода — не утверждает ли ответ сделанное, чего в журнале нет.
Решает не словарь фраз (владелец 21.11: «не превратится в огромный словарь?»), а модель коротким вопросом с журналом перед
глазами — на любом языке и при любой формулировке. Словами здесь — только грубый отбор, стоит ли вообще спрашивать: в ответе
есть «сделал / отправил / готово…» (несколько основ на русском и английском) — иначе вопроса нет и задержки тоже.
Расхождение — правдой из журнала: «Поправлюсь: …». За переключателем llm.ledger (замер на стенде: группы «Честность»,
«Действия», «Напоминания»)."""
import json
import re

# грубый отбор «ответ, похоже, говорит о сделанном» — только чтобы не спрашивать модель зря
MAYBE = re.compile(r"(?i)(?<![а-яёa-z])(?:готово|сделал\w*|выполнил\w*|включил\w*|запустил\w*|отправил\w*|написал\w*|записал\w*|"
                   r"сохранил\w*|поставил\w*|добавил\w*|удалил\w*|открыл\w*|позвонил\w*|создал\w*|напомню|включаю|отправляю|"
                   r"запускаю|открываю|звоню|ставлю|done|sent|added|saved|opened|created|deleted|started|turned on|playing|"
                   r"i(?:'ve| have) (?:set|sent|added|saved|opened|created))(?![а-яёa-z])")

# Просьба СДЕЛАТЬ (повелительное и «можешь …?»). Нет её, а это вопрос («где мои данные?», «что ты умеешь?», «что за
# значки?») — ответ рассказывает, а не отчитывается: стенд 26.11, судья Gemini — верные ответы портило «Поправлюсь: на
# самом деле это не сделано…» (модель-проверка приняла «заметки лежат на компьютере» за сделанное сейчас)
DO_ASK = re.compile(r"(?i)(?<![а-яёa-z])(?:постав|включ|выключ|отправ|напиш|запиш|сохран|откр|удал|добав|созда|позвон|напомн|"
                    r"сдела|запуст|убер|помен|измен|отмет|перенес|закаж|переда|скажи|пришл|скин|купи|заплат|оплат|забронир|"
                    r"переведи|play|send|set|open|turn|call|remind|save|add|delete|create|start)\w*(?![а-яёa-z])")
QUESTION = re.compile(r"(?i)^\s*(?:а\s+|и\s+|так\s+|слушай,?\s+)?(?:что|где|как|какие|какой|какая|какое|почему|зачем|сколько|"
                      r"когда|кто|чем|откуда|можно ли|правда ли|ты\s+(?:умеешь|можешь|знаешь|помнишь)|what|where|how|why|which|who|when)(?![а-яёa-z])")


# Просьба ПОКАЗАТЬ или НАЙТИ — тоже сведения (стенд Б 26.11, notes_show: «Покажи заметки» — верный список, и в конце «Поправлюсь:
# на самом деле это не сделано — записала обои…»: модель-проверка приняла содержимое заметки за сделанное сейчас)
READ_ASK = re.compile(r"(?i)^\s*(?:[а-яё]+[,!]\s+)?(?:а\s+|и\s+)?(?:покаж|найд|прочита|прочти|расскаж|перескаж|посмотр|глян|"
                      r"выведи|перечисл|напомни,?\s+(?:что|какие|о чём|о чем)|show|find|read|list|tell)\w*(?![а-яёa-z])")


def info_ask(ask):
    """Вопрос о сведениях или просьба показать и найти, без просьбы что-то сделать — ответ не утверждает «сделала»,
    ворота не нужны."""
    a = str(ask or "").strip()
    return bool(a) and not DO_ASK.search(a) and (a.endswith("?") or bool(QUESTION.search(a)) or bool(READ_ASK.search(a)))


PROMPT = ("Проверка честности ответа ассистента. Ниже — просьба человека, ответ ассистента и журнал: что программа на самом "
          "деле сделала в этом ходе. Утверждает ли ответ, что ассистент уже что-то СДЕЛАЛ или ДЕЛАЕТ сейчас (включил, отправил, "
          "написал, записал, поставил, открыл, позвонил, удалил, создал…), чего нет в журнале как выполненного или что в журнале "
          "не вышло? Обещание на будущее («могу», «если хотите»), вопрос, совет, рассказ о мире и рассказ о том, как устроена "
          "программа и что она умеет вообще («заметки хранятся на компьютере», «я включаю радио по просьбе»), пересказ того, что "
          "программа нашла или прочитала в этом ходе (заметки, напоминания, файлы, страницы), и то, что сделал сам человек, — не в счёт. Ответь одной "
          "строкой JSON без пояснений: {\"unbacked\": [\"коротко, что утверждается без основания\"]} — пустой список, если всё "
          "сходится.")


def on(value, prof):
    """Включены ли ворота хода: llm.ledger True/False — всегда/никогда; "auto" (по умолчанию с 1.0.69) — у облака Dewiar."""
    if value == "auto":
        return bool(isinstance(prof, dict) and prof.get("cloud"))
    return bool(value)


# указания модели в итоге действия («Подтверди коротко одной фразой.») — не про сделанное; в журнал проверки не нужны
_HINT = re.compile(r"[;,]?\s*(?:Подтверди[^.]*|Скажи (?:это|так)[^.]*|можно так и сказать|так и скажи)[.;]?", re.I)


def journal_text(acts):
    """Итог действия — до 400 знаков (стенд Б 26.11: «Вложения из сообщения приложены к напоминанию» стояло после 140-го
    знака, и проверка сочла «скрин будет в окне напоминания» неправдой)."""
    if not acts:
        return "- в этом ходе программа ничего не выполняла"
    return "\n".join(f"- {a.get('title') or a.get('name')}: {'сделано' if a.get('ok') else 'НЕ вышло'}"
                     + (f" ({_HINT.sub('', str(a.get('result'))).strip()[:400]})" if a.get("result") else "") for a in acts[:12])


def need_check(answer):
    a = (answer or "").strip()
    return bool(a) and len(a) <= 1500 and bool(MAYBE.search(a))


def parse(raw):
    """Ответ модели -> список утверждений без основания (что не разобрали — пусто: ворота не мешают ответу)."""
    m = re.search(r"\{.*\}", str(raw or ""), re.S)
    if not m:
        return []
    try:
        v = json.loads(m.group(0)).get("unbacked") or []
    except (ValueError, AttributeError):
        return []
    return [str(x).strip()[:160] for x in v if str(x).strip()][:3]


# Стенд В 26.11 (sit_come_back): «Бюджет — 40 тысяч на двоих. Продолжим?» — вопрос лишь по знаку «?», и «Каркас хода» молчал,
# а ответ кончался «сохранила план в заметке „Казань на выходные“» — без единого действия. Такой вопрос (без «что / где / как»
# и не «покажи») — не повод не проверять, если ответ сам говорит от первого лица «сохранила / записала…» («ты записал» в
# пересказе заметки — не про неё)
_DONE = re.compile(r"(?<![а-яё])(?:сохранил|записал|поставил|отправил|создал|добавил|удалил|перенес|перенёс|включил|выключил|"
                   r"запустил|отметил|переименовал|скачал|загрузил|настроил|завел|завёл)(?:а|и)?(?![а-яё])", re.I)
_NOT_ME = re.compile(r"(?:^|\s)(?:ты|вы|он|она|они|кто-то|человек)\s+(?:уже\s+|сам[аи]?\s+|тогда\s+)?$", re.I)


def says_done(answer):
    """В ответе — «сделала» от первого лица (не «ты записал», не «он добавил»)."""
    a = str(answer or "")
    return any(not _NOT_ME.search(a[max(0, m.start() - 24):m.start()]) for m in _DONE.finditer(a))


def check(ask, answer, acts, call):
    """call(system, user) -> текст ответа модели. -> список утверждений без основания ([] — всё сходится или проверка не нужна)."""
    a = str(ask or "")
    if not need_check(answer) or (info_ask(a) and not (says_done(answer) and not QUESTION.search(a) and not READ_ASK.search(a))):
        return []
    user = f"Просьба человека: {str(ask or '')[:600]}\n\nОтвет ассистента: {answer.strip()[:1500]}\n\nЖурнал хода:\n{journal_text(acts)}"
    try:
        return parse(call(PROMPT, user))
    except Exception:  # noqa: BLE001 — проверка не должна ломать ответ
        return []


def honest(unbacked, acts):
    """Поправка правдой: что на самом деле — из журнала."""
    failed = [a for a in acts or [] if not a.get("ok")]
    what = "; ".join(unbacked)
    tail = (" Не вышло: " + "; ".join(f"{a.get('title') or a.get('name')} — {str(a.get('result') or 'ошибка')[:120]}" for a in failed[:2]) + ".") if failed else ""
    return f"Поправлюсь: на самом деле это не сделано — {what}.{tail} Скажите, если попробовать ещё раз."
