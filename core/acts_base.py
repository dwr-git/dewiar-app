def confirm_word(text):
    """Короткий ответ «да / нет» -> True, False или None (это не ответ на вопрос)."""
    t = str(text or "").lower().replace("ё", "е").strip()
    if t.endswith("?"):                                # «а можно подробнее?», «ты точно уверена?» — вопрос, а не ответ
        return None
    if _CONFIRM_YES_RX.search(t):
        return True
    w = set(re.findall(r"[\wё-]+", t)) | set(re.findall(r"[\wё]+", t))
    if w & CONFIRM_NO:
        return False
    if w & CONFIRM_YES:
        return True
    return None


def _att_word(att):
    """[{kind…}] -> «2 картинки», «картинка и файл» — для уведомлений."""
    def plural(n, one, few, many):
        return one if n % 10 == 1 and n % 100 != 11 else few if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14 else many
    pics = sum(1 for f in att if f["kind"] == "image")
    files = len(att) - pics
    parts = []
    if pics:
        parts.append(f"{pics} " + plural(pics, "картинка", "картинки", "картинок"))
    if files:
        parts.append(f"{files} " + plural(files, "файл", "файла", "файлов"))
    return " и ".join(parts)


