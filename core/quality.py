def agenda_invented(answer, agenda, now=None):
    """Время в ответе о планах, которого нет ни в делах, ни сейчас -> подсказка или ""."""
    if not agenda or not answer:
        return ""
    import datetime as _dt
    now = now or _dt.datetime.now()
    have = {f"{int(h):02d}:{m}" for h, m in _HM.findall(agenda)}
    near = {(now + _dt.timedelta(minutes=d)).strftime("%H:%M") for d in range(-3, 4)}
    bad = []
    # рецензия 0.82: «после 12:00 вы свободны», «до 18:00», «могу напомнить в 9:30?», «предлагаю перенести на 15:00» — это
    # не дело из планов, а свободное время или предложение: такие времена (и всё в вопросах) не проверяем
    for sent in re.split(r"(?<=[.!?])\s+|\n+", answer):
        if "?" in sent:
            continue
        for part in re.split(r"[,;—–]|\s-\s", sent):
            if _AGENDA_FREE.search(part):
                continue
            bad += [f"{int(h):02d}:{m}" for h, m in _HM.findall(part) if f"{int(h):02d}:{m}" not in have | near]
    if not bad:
        return ""
    return (f"ПРОВЕРКА: в ответе о планах есть {bad[0]}, а в делах и календаре (справка к вопросу) такого времени нет — "
            "похоже, дело выдумано. Ответь ещё раз строго по справке: только дела оттуда, с их временем; ничего не добавляй.")


