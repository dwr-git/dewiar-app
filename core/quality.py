# «Напиши четверостишие с настоящей рифмой» — пять строк, «тишина — вода», «траве — мае»
POEM_LINES = {"двустиш": 2, "четверостиш": 4, "пятистиш": 5, "шестистиш": 6, "восьмистиш": 8, "хокку": 3, "хайку": 3, "лимерик": 5}
_VOW = "аеёиоуыэюя"
# созвучие на слух: безударные гласные и оглушение на конце не различаем, мягкий знак не звучит отдельно
_SOUND = str.maketrans({"ё": "и", "е": "и", "ы": "и", "э": "и", "я": "а", "о": "а", "ю": "у", "д": "т", "г": "к", "з": "с", "б": "п",
                        "в": "ф", "ж": "ш", "ь": None, "ъ": None})


def _ending(line):
    """Окончание строки для рифмы: от последней гласной до конца; открытый слог — с согласной перед гласной."""
    w = re.findall(r"[а-яё]+", (line or "").lower())
    if not w:
        return ""
    w = w[-1]
    i = max(w.rfind(v) for v in _VOW)
    if i < 0:
        return w[-2:]
    k = w[i:]
    if len(k.rstrip("ьъ")) == 1 and i > 0:
        k = w[i - 1:]
    return k


def _rhymes(a, b):
    ea, eb = _ending(a), _ending(b)
    return bool(ea and eb) and ea.translate(_SOUND) == eb.translate(_SOUND)


