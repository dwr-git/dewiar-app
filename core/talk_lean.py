def ordered(text):
    """Есть ли в реплике просьба-действие по форме: повелительное наклонение (помаши, отметь, погаси, выполните) или
    неопределённая форма с приставкой («выключить»). Разговорные «расскажи», «объясни», «давай» — не в счёт (_NOT_ORDER)."""
    t = (text or "").lower().replace("ё", "е")
    for w in re.findall(r"[а-я]+", t):
        if len(w) < 4 or w in _NOT_ORDER:
            continue
        if (len(w) >= 6 and re.search(r"(?:ите|йте|ьте)$", w)
                or len(w) >= 5 and re.search(r"[^аеиоуыэюяй](?:ай|яй|уй|юй)$", w)
                or re.match(r"^(?:по|при|от|за|вы|у|до|на|пере|раз|рас|вз|вс|под|об|из|про|в|вк|с)[а-я]{2,}[бвгджзклмнпрстфхцчшщ][иь]$", w)
                or re.match(r"^(?:по|при|от|за|вы|у|до|на|пере|раз|рас|под|об|из|про|вк|с)[а-я]{2,}(?:ить|ать|ять|еть|ти|чь)$", w)):
            return True
    return False


def talk_turn(text, history=(), packs=()):
    """Беседа ли это, где действия не нужны. text — реплика человека (без справки), history — последние сообщения разговора,
    packs — пачки действий, подобранные к вопросу (modules.wanted). Сомнение — False (полная подсказка)."""
    t = (text or "").split("\n\nВложения:")[0].strip()
    if not t or "\n\nВложения:" in (text or "") or len(t) > 1200:
        return False
    if packs or DEED.search(t) or TOOLS_ASK.search(t) or ordered(t):
        return False
    for m in list(history or ())[-4:]:                # идёт работа (действия в последних репликах) — не облегчаем
        if m.get("role") == "tool" or m.get("tool_calls"):
            return False
        c = m.get("content")
        if isinstance(c, str) and "выполнено инструментами" in c:
            return False
    return True


